// ============================================================
// RETURN CATEGORY INFORMATION
// ============================================================

CategoryInfo GetCategoryInfo(uint8_t tid)
{
    switch (tid)
    {
    case 0:
        return {0, "AC_BE (Best Effort)", AC_BE};

    case 1:
        return {1, "AC_BK (Background)", AC_BK};

    case 4:
        return {4, "AC_VI (Video)", AC_VI};

    case 6:
        return {6, "AC_VO (Voice)", AC_VO};

    default:
        return {0, "AC_BE (Best Effort)", AC_BE};
    }
}

// ============================================================
// RANDOM CATEGORY ASSIGNMENT
//
// IMPORTANT:
// One category is selected for a traffic stream.
// It remains frozen for every packet generated by
// that stream during the entire simulation.
//
// A new run can receive a different assignment.
// ============================================================

uint8_t RandomCategoryTid()
{
    std::random_device rd;
    std::mt19937 generator(rd());

    std::uniform_int_distribution<int> distribution(0, 3);

    int choice = distribution(generator);

    switch (choice)
    {
    case 0:
        return 0;   // AC_BE

    case 1:
        return 1;   // AC_BK

    case 2:
        return 4;   // AC_VI

    case 3:
        return 6;   // AC_VO

    default:
        return 0;   // AC_BE
    }
}

// ============================================================
// CUSTOM UDP APPLICATION
//
// This application is used because we need to attach the
// frozen QoS priority to every generated packet while keeping
// the traffic workload/rate controlled by our scenario.
//
// The actual EDCA backoff and channel access are still handled
// completely by ns-3.
// ============================================================

class FrozenQosUdpApplication : public Application
{
public:
    FrozenQosUdpApplication();

    static TypeId GetTypeId();

    void Setup(
        Address remote,
        uint32_t packetSize,
        uint64_t totalBytes,
        DataRate dataRate,
        uint8_t tid);

private:
    void StartApplication() override;
    void StopApplication() override;
    void DoDispose() override;

    void SendPacket();

    Ptr<Socket> m_socket;
    Address m_remote;

    uint32_t m_packetSize;
    uint64_t m_totalBytes;
    uint64_t m_bytesSent;

    DataRate m_dataRate;

    uint8_t m_tid;

    uint32_t m_sequence;

    EventId m_sendEvent;
};

// ============================================================
// TYPE ID
// ============================================================

TypeId
FrozenQosUdpApplication::GetTypeId()
{
    static TypeId tid =
        TypeId("ns3::FrozenQosUdpApplication")
            .SetParent<Application>()
            .SetGroupName("Applications")
            .AddConstructor<FrozenQosUdpApplication>();

    return tid;
}

// ============================================================
// CONSTRUCTOR
// ============================================================

FrozenQosUdpApplication::FrozenQosUdpApplication()
    : m_socket(nullptr),
      m_packetSize(0),
      m_totalBytes(0),
      m_bytesSent(0),
      m_dataRate(0),
      m_tid(0),
      m_sequence(0)
{
}

// ============================================================
// SETUP
// ============================================================

void
FrozenQosUdpApplication::Setup(
    Address remote,
    uint32_t packetSize,
    uint64_t totalBytes,
    DataRate dataRate,
    uint8_t tid)
{
    m_remote = remote;
    m_packetSize = packetSize;
    m_totalBytes = totalBytes;
    m_dataRate = dataRate;
    m_tid = tid;

    m_bytesSent = 0;
    m_sequence = 0;
}

// ============================================================
// START
// ============================================================

void
FrozenQosUdpApplication::StartApplication()
{
    m_socket =
        Socket::CreateSocket(
            GetNode(),
            UdpSocketFactory::GetTypeId());

    m_socket->SetAllowBroadcast(true);

    m_socket->Bind();

    m_socket->Connect(m_remote);

    // --------------------------------------------------------
    // THIS IS THE QoS CLASSIFICATION
    //
    // The socket priority is attached to outgoing packets by
    // the ns-3 UDP socket implementation.
    //
    // EDCA then uses this priority/TID to select the proper
    // Access Category.
    // --------------------------------------------------------

    m_socket->SetPriority(m_tid);

    // Start generating packets immediately when this
    // application reaches its configured start time.
    m_sendEvent =
        Simulator::ScheduleNow(
            &FrozenQosUdpApplication::SendPacket,
            this);
}

// ============================================================
// SEND PACKET
// ============================================================

void
FrozenQosUdpApplication::SendPacket()
{
    if (m_bytesSent >= m_totalBytes)
    {
        return;
    }

    // --------------------------------------------------------
    // IMPORTANT:
    //
    // We keep the packet size fixed at 1200 bytes, matching
    // the DCF baseline.
    //
    // Like the baseline OnOff application, the final packet
    // can make the generated total slightly exceed the
    // requested workload because complete packets are sent.
    // --------------------------------------------------------

    uint32_t bytesThisPacket =
        m_packetSize;

    // --------------------------------------------------------
    // SeqTsSizeHeader is included so the receiver can identify
    // the application packet sequence/timestamp just as in
    // the baseline experiment.
    // --------------------------------------------------------

    SeqTsSizeHeader header;

    header.SetSeq(m_sequence++);

    header.SetSize(
        bytesThisPacket);

    NS_ABORT_IF(
        bytesThisPacket <
        header.GetSerializedSize());

    Ptr<Packet> packet =
        Create<Packet>(
            bytesThisPacket -
            header.GetSerializedSize());

    packet->AddHeader(header);

    int actual =
        m_socket->Send(packet);

    if (actual ==
        static_cast<int>(bytesThisPacket))
    {
        m_bytesSent +=
            bytesThisPacket;

        // ----------------------------------------------------
        // Generate the next packet according to the configured
        // application data-generation rate.
        // ----------------------------------------------------

        double secondsPerPacket =
            (static_cast<double>(bytesThisPacket) * 8.0)
            /
            static_cast<double>(
                m_dataRate.GetBitRate());

        m_sendEvent =
            Simulator::Schedule(
                Seconds(secondsPerPacket),
                &FrozenQosUdpApplication::SendPacket,
                this);
    }
    else
    {
        // UDP normally accepts the packet into its socket
        // buffer. If it cannot accept it immediately, retry
        // shortly rather than inventing any Wi-Fi behavior.
        m_sendEvent =
            Simulator::Schedule(
                MicroSeconds(1),
                &FrozenQosUdpApplication::SendPacket,
                this);
    }
}

// ============================================================
// STOP
// ============================================================

void
FrozenQosUdpApplication::StopApplication()
{
    if (m_sendEvent.IsPending())
    {
        Simulator::Cancel(m_sendEvent);
    }

    if (m_socket)
    {
        m_socket->Close();
    }
}

// ============================================================
// DISPOSE
// ============================================================

void
FrozenQosUdpApplication::DoDispose()
{
    if (m_socket)
    {
        m_socket->Close();
        m_socket = nullptr;
    }

    Application::DoDispose();
}

// ============================================================
// INSTALL TRAFFIC
// ============================================================

void
InstallTraffic(
    Ptr<Node> sourceNode,
    Ipv4Address destination,
    uint16_t port,
    const TrafficConfig& config,
    uint8_t tid)
{
    Address remoteAddress(
        InetSocketAddress(
            destination,
            port));

    Ptr<FrozenQosUdpApplication> application =
        CreateObject<FrozenQosUdpApplication>();

    application->Setup(
        remoteAddress,
        PACKET_SIZE,
        config.totalBytes,
        DataRate(config.dataRate),
        tid);

    sourceNode->AddApplication(
        application);

    application->SetStartTime(
        Seconds(config.startTime));
}

// ============================================================
// PRINT TRAFFIC
// ============================================================

void
PrintTraffic(
    const std::string& name,
    const TrafficConfig& config)
{
    double megabytes =
        static_cast<double>(
            config.totalBytes)
        /
        1000000.0;

    uint64_t expectedPackets =
        static_cast<uint64_t>(
            std::ceil(
                static_cast<double>(
                    config.totalBytes)
                /
                PACKET_SIZE));

    std::cout
        << name
        << ": "
        << megabytes
        << " MB, "
        << config.dataRate
        << ", "
        << PACKET_SIZE
        << " B packets, "
        << expectedPackets
        << " packets, start "
        << config.startTime
        << " s"
        << std::endl;
}

// ============================================================
// PHY TRANSMISSION LOG
// ============================================================

bool firstDataTxObserved = false;

void
PhyTxBeginA(
    std::string context,
    Ptr<const Packet> packet,
    double txPowerW)
{
    if (!packet ||
        Simulator::Now().GetSeconds()
            < measurementStartTime)
    {
        return;
    }

    WifiMacHeader header;

    bool isData =
        packet->PeekHeader(header)
        &&
        header.IsData();

    if (!isData)
    {
        return;
    }

    std::cout
        << "[PHY-TX-DATA] "
        << Simulator::Now().GetSeconds()
        << " s | STA A | packet UID="
        << packet->GetUid()
        << " | size="
        << packet->GetSize()
        << " bytes"
        << std::endl;

    if (!firstDataTxObserved)
    {
        firstDataTxObserved = true;

        std::cout
            << "[FIRST-DATA-TX] "
            << Simulator::Now().GetSeconds()
            << " s | STA A transmitted first."
            << std::endl;
    }
}

