// ============================================================
// MAC FAILURE CALLBACKS
// ============================================================

void
MacDataFailed(
    std::string context,
    Mac48Address address)
{
    if (Simulator::Now().GetSeconds()
        >= measurementStartTime)
    {
        macDataFailures++;
    }
}

void
MacFinalDataFailed(
    std::string context,
    Mac48Address address)
{
    if (Simulator::Now().GetSeconds()
        >= measurementStartTime)
    {
        macFinalDataFailures++;
    }
}

// ============================================================
// QUEUE CALLBACKS
// ============================================================

void
QueueEnqueue(
    Ptr<const WifiMpdu> item)
{
    if (item)
    {
        queueEntryTimes[
            PeekPointer(item)] =
            Simulator::Now();
    }
}

void
QueueDequeue(
    Ptr<const WifiMpdu> item)
{
    if (!item)
    {
        return;
    }

    auto it =
        queueEntryTimes.find(
            PeekPointer(item));

    if (it != queueEntryTimes.end())
    {
        Time waitingTime =
            Simulator::Now()
            -
            it->second;

        queueWaitTotal +=
            waitingTime.GetSeconds();

        queueWaitSamples++;

        queueEntryTimes.erase(it);
    }
}

// ============================================================
// QUEUE MONITOR
// ============================================================

void
MonitorQueues(
    Ptr<WifiMacQueue> queueA,
    Ptr<WifiMacQueue> queueB)
{
    uint32_t currentA = 0;
    uint32_t currentB = 0;

    if (queueA)
    {
        currentA =
            queueA->GetNPackets();

        queueSamplesA +=
            currentA;

        if (currentA > maxQueueA)
        {
            maxQueueA = currentA;
        }
    }

    if (queueB)
    {
        currentB =
            queueB->GetNPackets();

        queueSamplesB +=
            currentB;

        if (currentB > maxQueueB)
        {
            maxQueueB = currentB;
        }
    }

    queueSampleCount++;

    Simulator::Schedule(
        MilliSeconds(1),
        &MonitorQueues,
        queueA,
        queueB);
}

// ============================================================
// MAIN
// ============================================================

int
main(
    int argc,
    char* argv[])
{
    uint32_t scenario = 1;
    uint32_t runNumber = 1;

    CommandLine cmd(__FILE__);

    cmd.AddValue(
        "scenario",
        "Scenario number: 1 to 5",
        scenario);

    cmd.AddValue(
        "run",
        "Random run number",
        runNumber);

    cmd.Parse(argc, argv);

    if (scenario < 1 ||
        scenario > 5)
    {
        std::cerr
            << "Scenario must be between 1 and 5."
            << std::endl;

        return 1;
    }

    // ========================================================
    // RANDOMNESS
    // ========================================================

    RngSeedManager::SetSeed(12345);

    RngSeedManager::SetRun(
        runNumber);

    // ========================================================
    // RANDOM / FROZEN EDCA CATEGORY
    // ========================================================

    uint8_t categoryA =
    RandomCategoryTid();

uint8_t categoryB =
    RandomCategoryTid();

    CategoryInfo infoA =
        GetCategoryInfo(categoryA);

    CategoryInfo infoB =
        GetCategoryInfo(categoryB);

    // ========================================================
    // CREATE NODES
    // ========================================================

    NodeContainer staNodes;

    staNodes.Create(2);

    NodeContainer apNode;

    apNode.Create(1);

    // ========================================================
    // WIFI CHANNEL
    // ========================================================

    YansWifiChannelHelper channel =
        YansWifiChannelHelper::Default();

    YansWifiPhyHelper phy;

    phy.SetChannel(
        channel.Create());

    // ========================================================
    // WIFI
    // ========================================================

    WifiHelper wifi;

    wifi.SetStandard(
        WIFI_STANDARD_80211n);

    // ========================================================
    // EDCA / QoS STA MAC
    //
    // QosSupported = true
    //
    // This enables the existing QoS/EDCA mechanism.
    // We do NOT implement our own backoff.
    // ========================================================

    WifiMacHelper mac;

    Ssid ssid =
        Ssid("AI-WIFI-NETWORK");

    mac.SetType(
        "ns3::StaWifiMac",
        "Ssid",
        SsidValue(ssid),
        "ActiveProbing",
        BooleanValue(false),
        "QosSupported",
        BooleanValue(true));

    NetDeviceContainer staDevices =
        wifi.Install(
            phy,
            mac,
            staNodes);

    // ========================================================
    // AP
    // ========================================================

    mac.SetType(
        "ns3::ApWifiMac",
        "Ssid",
        SsidValue(ssid),
        "QosSupported",
        BooleanValue(true));

    NetDeviceContainer apDevice =
        wifi.Install(
            phy,
            mac,
            apNode);

    // ========================================================
    // MOBILITY
    // ========================================================

    MobilityHelper mobility;

    mobility.SetMobilityModel(
        "ns3::ConstantPositionMobilityModel");

    mobility.Install(staNodes);

    mobility.Install(apNode);

    apNode.Get(0)
        ->GetObject<MobilityModel>()
        ->SetPosition(
            Vector(
                0.0,
                0.0,
                0.0));

    staNodes.Get(0)
        ->GetObject<MobilityModel>()
        ->SetPosition(
            Vector(
                5.0,
                0.0,
                0.0));

    staNodes.Get(1)
        ->GetObject<MobilityModel>()
        ->SetPosition(
            Vector(
                -5.0,
                0.0,
                0.0));

    // ========================================================
    // INTERNET
    // ========================================================

    InternetStackHelper internet;

    internet.Install(staNodes);

    internet.Install(apNode);

    // ========================================================
    // IP ADDRESSES
    // ========================================================

    Ipv4AddressHelper ipv4;

    ipv4.SetBase(
        "192.168.1.0",
        "255.255.255.0");

    Ipv4InterfaceContainer staInterfaces =
        ipv4.Assign(staDevices);

    Ipv4InterfaceContainer apInterfaces =
        ipv4.Assign(apDevice);

    Ipv4Address apAddress =
        apInterfaces.GetAddress(0);

    // ========================================================
    // SCENARIO CONFIGURATION
    // ========================================================

    TrafficConfig trafficA;
    TrafficConfig trafficB;

    trafficA.totalBytes = 0;
    trafficB.totalBytes = 0;

    // --------------------------------------------------------
    // SCENARIO 1
    // Simple separate traffic
    // --------------------------------------------------------

    if (scenario == 1)
    {
        trafficA =
            {
                2 * 1000 * 1000,
                "2Mbps",
                1.0
            };

        trafficB =
            {
                2 * 1000 * 1000,
                "2Mbps",
                5.0
            };

        measurementStartTime = 1.0;
    }

    // --------------------------------------------------------
    // SCENARIO 2
    // Simultaneous same-load traffic
    // --------------------------------------------------------

    else if (scenario == 2)
    {
        trafficA =
            {
                5 * 1000 * 1000,
                "10Mbps",
                1.0
            };

        trafficB =
            {
                5 * 1000 * 1000,
                "10Mbps",
                1.0
            };

        measurementStartTime = 1.0;
    }

    // --------------------------------------------------------
    // SCENARIO 3
    // Sudden asymmetric load
    // --------------------------------------------------------

    else if (scenario == 3)
    {
        trafficA =
            {
                4 * 1000 * 1000,
                "2Mbps",
                1.0
            };

        trafficB =
            {
                12 * 1000 * 1000,
                "20Mbps",
                3.0
            };

        measurementStartTime = 1.0;
    }

    // --------------------------------------------------------
    // SCENARIO 4
    // Simultaneous heavy traffic
    // --------------------------------------------------------

    else if (scenario == 4)
    {
        trafficA =
            {
                20 * 1000 * 1000,
                "20Mbps",
                1.0
            };

        trafficB =
            {
                20 * 1000 * 1000,
                "20Mbps",
                1.0
            };

        measurementStartTime = 1.0;
    }

    // --------------------------------------------------------
    // SCENARIO 5
    // Dynamic / changing traffic
    //
    // A starts with heavy traffic.
    // B starts with heavy traffic.
    // B receives another workload later.
    // --------------------------------------------------------

    else if (scenario == 5)
    {
        trafficA =
            {
                50 * 1000 * 1000,
                "40Mbps",
                1.0
            };

        trafficB =
            {
                50 * 1000 * 1000,
                "40Mbps",
                1.0
            };

        measurementStartTime = 1.0;
    }

    // ========================================================
    // INITIAL CONFIGURATION
    // ========================================================

    std::cout << std::endl;

    std::cout
        << "=================================================="
        << std::endl;

    std::cout
        << "             WIFI EDCA"
        << std::endl;

    std::cout
        << "=================================================="
        << std::endl;

    std::cout
        << "Scenario       : "
        << scenario
        << std::endl;

    std::cout
        << "Random Run     : "
        << runNumber
        << std::endl;

    std::cout
        << "Packet Size    : "
        << PACKET_SIZE
        << " bytes"
        << std::endl;

    std::cout
        << "Simulation Time: "
        << SIMULATION_TIME
        << " seconds"
        << std::endl;

    std::cout << std::endl;

    PrintTraffic(
        "STA A",
        trafficA);

    PrintTraffic(
        "STA B",
        trafficB);

    std::cout << std::endl;

    // ========================================================
    // EDCA CATEGORY ASSIGNMENT
    // ========================================================

    std::cout
        << "============================================"
        << std::endl;

    std::cout
        << "          EDCA CONFIGURATION"
        << std::endl;

    std::cout
        << "============================================"
        << std::endl;

    std::cout
        << "STA A Access Category : "
        << infoA.name
        << std::endl;

    std::cout
        << "STA B Access Category : "
        << infoB.name
        << std::endl;

    std::cout
        << "Assignment            : Random / Frozen"
        << std::endl;

    std::cout
        << "============================================"
        << std::endl;

    std::cout << std::endl;

    // ========================================================
    // UDP SINKS
    // ========================================================

    uint16_t portA = 5000;
    uint16_t portB = 5001;

    PacketSinkHelper sinkA(
        "ns3::UdpSocketFactory",
        InetSocketAddress(
            Ipv4Address::GetAny(),
            portA));

    PacketSinkHelper sinkB(
        "ns3::UdpSocketFactory",
        InetSocketAddress(
            Ipv4Address::GetAny(),
            portB));

    sinkA.SetAttribute(
        "EnableSeqTsSizeHeader",
        BooleanValue(true));

    sinkB.SetAttribute(
        "EnableSeqTsSizeHeader",
        BooleanValue(true));

    ApplicationContainer sinkAppA =
        sinkA.Install(
            apNode.Get(0));

    ApplicationContainer sinkAppB =
        sinkB.Install(
            apNode.Get(0));

    sinkAppA.Start(
        Seconds(0.5));

    sinkAppB.Start(
        Seconds(0.5));

    // ========================================================
    // INSTALL MAIN TRAFFIC
    // ========================================================

    InstallTraffic(
        staNodes.Get(0),
        apAddress,
        portA,
        trafficA,
        categoryA);

    InstallTraffic(
        staNodes.Get(1),
        apAddress,
        portB,
        trafficB,
        categoryB);

    // ========================================================
    // SCENARIO 5 SECOND B BURST
    //
    // SAME B CATEGORY.
    //
    // The category belongs to the device's traffic stream
    // and remains frozen. The second workload does NOT
    // randomly change B's category.
    // ========================================================

    if (scenario == 5)
    {
        TrafficConfig secondBurst =
            {
                10 * 1000 * 1000,
                "10Mbps",
                6.0
            };

        InstallTraffic(
            staNodes.Get(1),
            apAddress,
            portB,
            secondBurst,
            categoryB);

        std::cout
            << "STA B second burst: "
            << "10 MB, 10Mbps, "
            << PACKET_SIZE
            << " B packets, start 6 s"
            << std::endl;

        std::cout
            << "STA B second burst category: "
            << infoB.name
            << std::endl;
    }

    // ========================================================
    // GET STA MAC QUEUES
    //
    // Because this is QoS/EDCA, we monitor the queue belonging
    // to each station's assigned Access Category.
    // ========================================================

    Ptr<WifiNetDevice> wifiStaA =
        DynamicCast<WifiNetDevice>(
            staDevices.Get(0));

    Ptr<WifiNetDevice> wifiStaB =
        DynamicCast<WifiNetDevice>(
            staDevices.Get(1));

    Ptr<WifiMac> macA =
        wifiStaA->GetMac();

    Ptr<WifiMac> macB =
        wifiStaB->GetMac();

    Ptr<WifiMacQueue> queueA =
        macA->GetTxopQueue(
            infoA.ac);

    Ptr<WifiMacQueue> queueB =
        macB->GetTxopQueue(
            infoB.ac);

    // ========================================================
    // QUEUE TRACES
    // ========================================================

    if (queueA)
    {
        queueA->TraceConnectWithoutContext(
            "Enqueue",
            MakeCallback(&QueueEnqueue));

        queueA->TraceConnectWithoutContext(
            "Dequeue",
            MakeCallback(&QueueDequeue));
    }

    if (queueB)
    {
        queueB->TraceConnectWithoutContext(
            "Enqueue",
            MakeCallback(&QueueEnqueue));

        queueB->TraceConnectWithoutContext(
            "Dequeue",
            MakeCallback(&QueueDequeue));
    }

    // ========================================================
    // PHY TRANSMISSION OBSERVATION
    // ========================================================

    Config::Connect(
        "/NodeList/0/DeviceList/0/"
        "$ns3::WifiNetDevice/Phy/PhyTxBegin",
        MakeCallback(&PhyTxBeginA));

    Config::Connect(
        "/NodeList/1/DeviceList/0/"
        "$ns3::WifiNetDevice/Phy/PhyTxBegin",
        MakeCallback(&PhyTxBeginB));

    std::cout
        << "[TRACE] Actual PHY transmission logging enabled."
        << std::endl;

    std::cout
        << "[TRACE] EDCA backoff and contention are handled"
        << std::endl;

    std::cout
        << "[TRACE] internally by ns-3."
        << std::endl;

    std::cout << std::endl;

    // ========================================================
    // QUEUE MONITOR
    // ========================================================

    Simulator::Schedule(
        MilliSeconds(1),
        &MonitorQueues,
        queueA,
        queueB);

    // ========================================================
    // MAC FAILURE TRACES
    // ========================================================

    Config::Connect(
        "/NodeList/*/DeviceList/*/"
        "RemoteStationManager/MacTxDataFailed",
        MakeCallback(&MacDataFailed));

    Config::Connect(
        "/NodeList/*/DeviceList/*/"
        "RemoteStationManager/MacTxFinalDataFailed",
        MakeCallback(&MacFinalDataFailed));

    // ========================================================
    // FLOW MONITOR
    // ========================================================

    FlowMonitorHelper flowHelper;

    Ptr<FlowMonitor> flowMonitor =
        flowHelper.InstallAll();

    // ========================================================
    // SIMULATION
    // ========================================================

    Simulator::Stop(
        Seconds(SIMULATION_TIME));

    Simulator::Run();

    // ========================================================
    // FINAL SIMULATION SUMMARY
    // ========================================================

    std::cout << std::endl;

    std::cout
        << "============================================"
        << std::endl;

    std::cout
        << "          SIMULATION SUMMARY"
        << std::endl;

    std::cout
        << "============================================"
        << std::endl;

    std::cout
        << "Scenario       : "
        << scenario
        << std::endl;

    std::cout
        << "Random Run     : "
        << runNumber
        << std::endl;

    std::cout
        << "Packet Size    : "
        << PACKET_SIZE
        << " bytes"
        << std::endl;

    std::cout
        << "Simulation Time: "
        << SIMULATION_TIME
        << " seconds"
        << std::endl;

    std::cout << std::endl;

    PrintTraffic(
        "STA A",
        trafficA);

    PrintTraffic(
        "STA B",
        trafficB);

    std::cout << std::endl;

    std::cout
        << "STA A EDCA Category: "
        << infoA.name
        << std::endl;

    std::cout
        << "STA B EDCA Category: "
        << infoB.name
        << std::endl;

    if (scenario == 5)
    {
        std::cout
            << "STA B second burst: "
            << "10 MB, 10Mbps, "
            << PACKET_SIZE
            << " B packets, start 6 s"
            << std::endl;

        std::cout
            << "STA B second burst category: "
            << infoB.name
            << std::endl;
    }

    std::cout
        << "============================================"
        << std::endl;

    // ========================================================
    // FLOW RESULTS
    // ========================================================

    flowMonitor->CheckForLostPackets();

    Ptr<Ipv4FlowClassifier> classifier =
        DynamicCast<Ipv4FlowClassifier>(
            flowHelper.GetClassifier());

    uint64_t totalTxPackets = 0;
    uint64_t totalRxPackets = 0;
    uint64_t totalLostPackets = 0;

    Time totalDelay =
        Seconds(0);

    std::cout << std::endl;

    std::cout
        << "=================================================="
        << std::endl;

    std::cout
        << "                 FLOW RESULTS"
        << std::endl;

    std::cout
        << "=================================================="
        << std::endl;

    for (const auto& flow :
         flowMonitor->GetFlowStats())
    {
        Ipv4FlowClassifier::FiveTuple tuple =
            classifier->FindFlow(
                flow.first);

        const FlowMonitor::FlowStats& stats =
            flow.second;

        totalTxPackets +=
            stats.txPackets;

        totalRxPackets +=
            stats.rxPackets;

        totalLostPackets +=
            stats.lostPackets;

        totalDelay +=
            stats.delaySum;

        std::cout
            << "Flow "
            << flow.first
            << ": "
            << tuple.sourceAddress
            << " -> "
            << tuple.destinationAddress
            << std::endl;

        std::cout
            << "  TX packets : "
            << stats.txPackets
            << std::endl;

        std::cout
            << "  RX packets : "
            << stats.rxPackets
            << std::endl;

        std::cout
            << "  Lost       : "
            << stats.lostPackets
            << std::endl;

        if (stats.rxPackets > 0)
        {
            double avgDelay =
                stats.delaySum.GetSeconds()
                /
                stats.rxPackets;

            std::cout
                << "  Avg latency: "
                << avgDelay * 1000.0
                << " ms"
                << std::endl;
        }

        if (stats.timeLastRxPacket >
            stats.timeFirstTxPacket)
        {
            double duration =
                stats.timeLastRxPacket.GetSeconds()
                -
                stats.timeFirstTxPacket.GetSeconds();

            double throughput =
                stats.rxBytes * 8.0
                /
                duration;

            std::cout
                << "  Throughput : "
                << throughput / 1000000.0
                << " Mbps"
                << std::endl;
        }

        std::cout << std::endl;
    }

    // ========================================================
    // OVERALL METRICS
    // ========================================================

    double averageLatencyMs = 0.0;

    if (totalRxPackets > 0)
    {
        averageLatencyMs =
            totalDelay.GetSeconds()
            /
            totalRxPackets
            *
            1000.0;
    }

    double packetLossPercentage = 0.0;

    if (totalTxPackets > 0)
    {
        packetLossPercentage =
            static_cast<double>(
                totalLostPackets)
            /
            static_cast<double>(
                totalTxPackets)
            *
            100.0;
    }

    double averageQueueA = 0.0;
    double averageQueueB = 0.0;

    if (queueSampleCount > 0)
    {
        averageQueueA =
            queueSamplesA
            /
            queueSampleCount;

        averageQueueB =
            queueSamplesB
            /
            queueSampleCount;
    }

    double averageCombinedQueue =
        averageQueueA
        +
        averageQueueB;

    double averageQueueWaitMs = 0.0;

    if (queueWaitSamples > 0)
    {
        averageQueueWaitMs =
            queueWaitTotal
            /
            queueWaitSamples
            *
            1000.0;
    }

    // ========================================================
    // FINAL EDCA RESULTS
    // ========================================================

    std::cout
        << "=================================================="
        << std::endl;

    std::cout
        << "                  FINAL EDCA"
        << std::endl;

    std::cout
        << "=================================================="
        << std::endl;

    std::cout
        << "Scenario                    : "
        << scenario
        << std::endl;

    std::cout
        << "Random run                  : "
        << runNumber
        << std::endl;

    std::cout
        << "STA A EDCA category         : "
        << infoA.name
        << std::endl;

    std::cout
        << "STA B EDCA category         : "
        << infoB.name
        << std::endl;

    std::cout
        << "Total TX packets            : "
        << totalTxPackets
        << std::endl;

    std::cout
        << "Total RX packets            : "
        << totalRxPackets
        << std::endl;

    std::cout
        << "Lost packets                : "
        << totalLostPackets
        << std::endl;

    std::cout
        << "Packet loss                 : "
        << packetLossPercentage
        << " %"
        << std::endl;

    std::cout
        << "Average latency             : "
        << averageLatencyMs
        << " ms"
        << std::endl;

    std::cout
        << "Average queue A             : "
        << averageQueueA
        << " packets"
        << std::endl;

    std::cout
        << "Average queue B             : "
        << averageQueueB
        << " packets"
        << std::endl;

    std::cout
        << "Average combined queue      : "
        << averageCombinedQueue
        << " packets"
        << std::endl;

    std::cout
        << "Maximum queue A             : "
        << maxQueueA
        << " packets"
        << std::endl;

    std::cout
        << "Maximum queue B             : "
        << maxQueueB
        << " packets"
        << std::endl;

    std::cout
        << "Average queue waiting time  : "
        << averageQueueWaitMs
        << " ms"
        << std::endl;

    std::cout
        << "MAC data failures           : "
        << macDataFailures
        << std::endl;

    std::cout
        << "MAC final failures          : "
        << macFinalDataFailures
        << std::endl;

    std::cout
        << "=================================================="
        << std::endl;

    Simulator::Destroy();

    return 0;
}